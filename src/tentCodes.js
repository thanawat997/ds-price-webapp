const CODE_BY_NAME = (() => {
  const map = new Map();
  for (const line of CODE_LINES) {
    const m = String(line).match(/^(\S+)\s+(.+)$/);
    if (!m) continue;
    const code = m[1];
    const name = normalizeName(m[2]);
    if (!name) continue;
    if (!map.has(name)) map.set(name, code);
  }
  return map;
})();

function getTentCode(tentName) {
  const key = normalizeName(tentName);
  return CODE_BY_NAME.get(key) || "";
}

function getCodeTentNameForSheet(tentName) {
  const code = getTentCode(tentName);
  if (!code) return "";
  return `${code} ${normalizeName(tentName)}`;
}

module.exports = { getTentCode, getCodeTentNameForSheet };
